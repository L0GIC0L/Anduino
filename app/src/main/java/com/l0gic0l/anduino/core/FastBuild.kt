package com.l0gic0l.anduino.core

import com.l0gic0l.anduino.env.ExecServer
import com.l0gic0l.anduino.env.LinuxEnv
import com.l0gic0l.anduino.env.NativeExec
import java.io.File

/**
 * `platform.local.txt` overrides that put the relay client in front of every build
 * recipe of a platform (compile, preprocess, archive, link, objcopy/esptool, size and
 * the bash/python hooks), so they run natively through [ExecServer]. arduino-cli merges
 * platform.local.txt over platform.txt; the library-detection pass derives its
 * preprocessor command from recipe.cpp.o.pattern unless the platform defines
 * recipe.preproc.macros, so detection is covered either way.
 */
object PlatformOverrides {
    const val MARKER = "# Generated by Anduino (fast native compiler). Delete to disable for this platform."

    /** recipe.<anything>.pattern and recipe.preproc.macros, plus their .linux variants. */
    private val RECIPE = Regex("""^recipe\.(?:.+\.pattern|preproc\.macros)(?:\.linux)?$""")

    /** The overrides for a platform.txt, or null if it has no recipes. */
    fun generate(platformTxt: String, client: String): String? {
        val props = LinkedHashMap<String, String>()
        for (raw in platformTxt.lineSequence()) {
            val line = raw.trim()
            if (line.isEmpty() || line.startsWith("#")) continue
            val i = line.indexOf('=')
            if (i <= 0) continue
            props[line.substring(0, i).trim()] = line.substring(i + 1).trim()
        }
        val out = StringBuilder(MARKER).append('\n')
        var any = false
        for ((key, value) in props) {
            if (!RECIPE.matches(key) || value.isBlank() || value.startsWith(client)) continue
            out.append(key).append('=').append(client).append(' ').append(value).append('\n')
            any = true
        }
        return if (any) out.toString() else null
    }
}

/**
 * Keeps the fast native compile path set up: glibc links, relay client, exec server,
 * and platform.local.txt for every installed core. Falls back silently: if anything
 * here is unavailable, the overrides are removed and builds run under proot.
 */
class FastBuild(
    private val env: LinuxEnv,
    private val native: NativeExec,
    private val server: ExecServer,
    private val console: ConsoleLog,
) {
    private var selfTested = false
    private var selfTestOk = false
    private var selfTestError = ""
    private var offReason: String? = null

    /** Prepares everything for a build; returns true if compilers will run natively. */
    fun prepare(enabled: Boolean): Boolean {
        server.resetStats()
        offReason = when {
            !enabled -> "off in Settings"
            !native.isAvailable -> "not included in this app build"
            server.disabled -> "turned off earlier in this session (${server.disabledReason})"
            !selfTest() -> "unavailable on this device ($selfTestError)"
            else -> null
        }
        if (offReason == null) {
            server.start()
            writeOverrides()
        } else {
            removeOverrides()
        }
        return offReason == null
    }

    /** One line saying how much of the last build ran natively, for the end of the output. */
    fun summary(): String {
        offReason?.let { return "Fast native compiler: $it. Every step ran under proot (slow)." }
        val reran = server.fallbacks
        val native = server.commandsRun - reran
        val sb = StringBuilder("Fast native compiler: $native steps ran natively")
        if (server.declined > 0) sb.append(", ${server.declined} could not (ran under proot)")
        if (reran > 0) sb.append(", $reran failed natively and were rerun under proot (${server.fallbackReasons.take(3).joinToString("; ")})")
        server.disabledReason?.let { sb.append("; then turned off: $it") }
        return sb.append('.').toString()
    }

    private fun selfTest(): Boolean {
        if (selfTested) return selfTestOk
        selfTested = true
        selfTestOk = try {
            native.install()
            val probe = File(native.root, "usr/bin/true")
            val p = native.processBuilder(probe.path, probe.path, emptyList(), File(native.root)).redirectErrorStream(true).start()
            val output = p.inputStream.bufferedReader().readText()
            val code = p.waitFor()
            if (code != 0) {
                selfTestError = "exit $code: ${output.trim().take(300)}"
                console.info("Fast native compiler unavailable on this device ($selfTestError)")
            }
            code == 0
        } catch (e: Exception) {
            selfTestError = e.message.orEmpty()
            console.info("Fast native compiler unavailable on this device: ${e.message}")
            false
        }
        if (selfTestOk) console.info("Fast native compiler enabled (compilers run outside the proot layer).")
        return selfTestOk
    }

    private fun platformDirs(): List<File> =
        env.packagesDir.listFiles().orEmpty()
            .flatMap { File(it, "hardware").listFiles().orEmpty().toList() }
            .flatMap { it.listFiles().orEmpty().toList() }
            .filter { File(it, "platform.txt").isFile }

    private fun writeOverrides() {
        for (dir in platformDirs()) {
            val local = File(dir, "platform.local.txt")
            if (local.exists() && !local.readText().startsWith(PlatformOverrides.MARKER)) continue // user's own
            val text = PlatformOverrides.generate(File(dir, "platform.txt").readText(), native.clientGuestPath) ?: continue
            if (!local.exists() || local.readText() != text) local.writeText(text)
        }
    }

    fun removeOverrides() {
        for (dir in platformDirs()) {
            val local = File(dir, "platform.local.txt")
            if (local.exists() && local.readText().startsWith(PlatformOverrides.MARKER)) local.delete()
        }
    }
}
