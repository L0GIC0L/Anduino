package com.l0gic0l.anduino.core

import com.l0gic0l.anduino.env.ExecServer
import com.l0gic0l.anduino.env.LinuxEnv
import com.l0gic0l.anduino.env.NativeExec
import java.io.File

/**
 * `platform.local.txt` overrides that put the relay client in front of a platform's
 * heavy recipes (compile, archive, link, preprocess), so they run natively through
 * [ExecServer]. arduino-cli merges platform.local.txt over platform.txt; the library
 * detection pass derives its preprocessor command from recipe.cpp.o.pattern unless the
 * platform defines recipe.preproc.macros, so detection is covered either way.
 */
object PlatformOverrides {
    const val MARKER = "# Generated by Anduino (fast native compiler). Delete to disable for this platform."

    private val KEYS = listOf(
        "recipe.c.o.pattern", "recipe.cpp.o.pattern", "recipe.S.o.pattern",
        "recipe.ar.pattern", "recipe.c.combine.pattern", "recipe.preproc.macros",
    )

    /** The overrides for a platform.txt, or null if it has none of the recipes. */
    fun generate(platformTxt: String, client: String): String? {
        val props = LinkedHashMap<String, String>()
        for (raw in platformTxt.lineSequence()) {
            val line = raw.trim()
            if (line.isEmpty() || line.startsWith("#")) continue
            val i = line.indexOf('=')
            if (i <= 0) continue
            props[line.substring(0, i).trim()] = line.substring(i + 1).trim()
        }
        val out = StringBuilder(MARKER).append('\n')
        var any = false
        for (key in KEYS) {
            for (k in listOf(key, "$key.linux")) {
                val value = props[k] ?: continue
                if (value.isBlank() || value.startsWith(client)) continue
                out.append(k).append('=').append(client).append(' ').append(value).append('\n')
                any = true
            }
        }
        return if (any) out.toString() else null
    }
}

/**
 * Keeps the fast native compile path set up: glibc links, relay client, exec server,
 * and platform.local.txt for every installed core. Falls back silently: if anything
 * here is unavailable, the overrides are removed and builds run under proot.
 */
class FastBuild(
    private val env: LinuxEnv,
    private val native: NativeExec,
    private val server: ExecServer,
    private val console: ConsoleLog,
) {
    private var selfTested = false
    private var selfTestOk = false

    /** Prepares everything for a build; returns true if compilers will run natively. */
    fun prepare(enabled: Boolean): Boolean {
        val usable = enabled && native.isAvailable && !server.disabled && selfTest()
        if (usable) {
            server.start()
            writeOverrides()
        } else {
            removeOverrides()
        }
        return usable
    }

    private fun selfTest(): Boolean {
        if (selfTested) return selfTestOk
        selfTested = true
        selfTestOk = try {
            native.install()
            val probe = File(native.root, "usr/bin/true")
            val p = native.processBuilder(probe.path, probe.path, emptyList(), File(native.root)).redirectErrorStream(true).start()
            val output = p.inputStream.bufferedReader().readText()
            val code = p.waitFor()
            if (code != 0) console.info("Fast native compiler unavailable on this device (exit $code): ${output.take(300)}")
            code == 0
        } catch (e: Exception) {
            console.info("Fast native compiler unavailable on this device: ${e.message}")
            false
        }
        if (selfTestOk) console.info("Fast native compiler enabled (compilers run outside the proot layer).")
        return selfTestOk
    }

    private fun platformDirs(): List<File> =
        env.packagesDir.listFiles().orEmpty()
            .flatMap { File(it, "hardware").listFiles().orEmpty().toList() }
            .flatMap { it.listFiles().orEmpty().toList() }
            .filter { File(it, "platform.txt").isFile }

    private fun writeOverrides() {
        for (dir in platformDirs()) {
            val local = File(dir, "platform.local.txt")
            if (local.exists() && !local.readText().startsWith(PlatformOverrides.MARKER)) continue // user's own
            val text = PlatformOverrides.generate(File(dir, "platform.txt").readText(), native.clientGuestPath) ?: continue
            if (!local.exists() || local.readText() != text) local.writeText(text)
        }
    }

    fun removeOverrides() {
        for (dir in platformDirs()) {
            val local = File(dir, "platform.local.txt")
            if (local.exists() && local.readText().startsWith(PlatformOverrides.MARKER)) local.delete()
        }
    }
}
